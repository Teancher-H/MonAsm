//! The sealed bundle's own identity: self-verification, the nine-key set, the
//! ownership map and the canonical output (`ADR-0128` §7, §8.2).
//!
//! The cross-language half of `the_output_is_canonical_json` is the fixed-vector
//! test in `n1a_digest.rs`: a Rust build and a Python `hashlib` check reproduce
//! the same metadata bytes and digests.

mod support;

use fmp_definition::error::BuildError;
use fmp_definition::SealedBundle;
use fmp_model::canonical::canonical_bytes;
use fmp_model::json::{self, Json};
use support::*;

fn with_extra(value: &Json, field: &str, extra: Json) -> Json {
    match value {
        Json::Object(entries) => {
            let mut entries = entries.clone();
            entries.push((field.to_string(), extra));
            Json::Object(entries)
        }
        other => other.clone(),
    }
}

fn zero_digest() -> String {
    format!("sha256:{}", "0".repeat(64))
}

fn owner(package_id: &str) -> Json {
    Json::Str(package_id.to_string())
}

fn owners_of(metadata: &Json) -> Vec<Json> {
    metadata
        .get("form_owners")
        .and_then(Json::as_array)
        .expect("the metadata carries form_owners")
        .to_vec()
}

/// Rebuild the sealed document around a rewritten ownership map.
///
/// The `bundle_digest` is recomputed over the rewritten metadata, so the only
/// remaining finding is the map itself — otherwise the digest would mask it.
fn reseal(sealed: &Json, owners: Json) -> Json {
    let parsed = SealedBundle::from_json(sealed.clone()).expect("the original sealed file parses");
    let metadata = json_set(
        &parsed.metadata().expect("metadata"),
        "form_owners",
        owners.clone(),
    );
    let digest = fmp_definition::digest::bundle_digest(&metadata);
    let resealed = json_set(sealed, "form_owners", owners);
    json_set(&resealed, "bundle_digest", Json::Str(digest))
}

fn reject(tampered: Json) -> BuildError {
    match SealedBundle::from_json(tampered) {
        Ok(bundle) => bundle
            .verify()
            .expect_err("a rewritten ownership map is not a complete bundle"),
        Err(error) => error,
    }
}

fn two_package_bundle(tree: &TempTree) -> (Json, ManifestFixture, ManifestFixture) {
    let a = ManifestFixture::default();
    let b = package_with(
        "monasm.x86.add-imm",
        &[("x86:add/rm64-imm8/legacy", "forms/add.json")],
        &["field-placement/v1", "integer-domain/v1"],
    );
    write_release_package(tree, &a);
    write_release_package(tree, &b);
    let spec = SpecFixture::for_packages(vec![
        SpecEntryFixture::of(tree, &b),
        SpecEntryFixture::of(tree, &a),
    ]);
    let bundle = checked(tree, &spec);
    (bundle.bundle_json(), a, b)
}

/// `the_builder_identity_is_not_part_of_the_definition_digest` — a builder
/// version is recorded in the lock and nowhere in the execution rules.
#[test]
fn the_builder_identity_is_not_part_of_the_definition_digest() {
    let tree = TempTree::new("builder-identity");
    let fixture = ManifestFixture::default();
    write_release_package(&tree, &fixture);
    let spec = SpecFixture::for_packages(vec![SpecEntryFixture::of(&tree, &fixture)]);
    let parsed = parse_spec(&spec).expect("the spec parses");

    let one = fmp_definition::CheckedBundle::build(
        tree.root(),
        &parsed,
        fmp_definition::Builder::new("fmp-definition", "0.0.1"),
    )
    .expect("build one");
    let two = fmp_definition::CheckedBundle::build(
        tree.root(),
        &parsed,
        fmp_definition::Builder::new("fmp-definition", "0.0.2").with_build("hash-2"),
    )
    .expect("build two");

    assert_eq!(one.definition_digest(), two.definition_digest());
    assert_eq!(one.bundle_digest(), two.bundle_digest());
    assert_eq!(
        canonical_bytes(&one.bundle_json()),
        canonical_bytes(&two.bundle_json()),
        "the sealed document has no builder field"
    );
    assert_ne!(
        canonical_bytes(&one.lock_json().get("builder").unwrap().clone()),
        canonical_bytes(&two.lock_json().get("builder").unwrap().clone())
    );
}

/// `the_output_is_canonical_json` — the generated bytes are whitespace-free,
/// key-sorted and newline-free, and re-canonicalising them is the identity.
#[test]
fn the_output_is_canonical_json() {
    let tree = TempTree::new("canonical-output");
    let fixture = ManifestFixture::default();
    write_release_package(&tree, &fixture);
    let spec = SpecFixture::for_packages(vec![SpecEntryFixture::of(&tree, &fixture)]);
    let bundle = checked(&tree, &spec);

    for value in [bundle.lock_json(), bundle.bundle_json()] {
        let bytes = canonical_bytes(&value);
        assert_eq!(bytes.first(), Some(&b'{'));
        assert_eq!(bytes.last(), Some(&b'}'), "no trailing newline");
        assert!(
            !bytes.iter().any(|byte| *byte == b'\n' || *byte == b'\r'),
            "a line break is insignificant whitespace"
        );
        let parsed = json::parse(&bytes).expect("the generated bytes parse");
        assert_eq!(canonical_bytes(&parsed), bytes);
        assert_sorted(&value, "");
    }
}

fn assert_sorted(value: &Json, pointer: &str) {
    match value {
        Json::Object(entries) => {
            for pair in entries.windows(2) {
                assert!(
                    pair[0].0 < pair[1].0,
                    "keys at {pointer:?} are not strictly sorted: {:?} then {:?}",
                    pair[0].0,
                    pair[1].0
                );
            }
            for (key, child) in entries {
                assert_sorted(child, &format!("{pointer}/{key}"));
            }
        }
        Json::Array(items) => {
            for (index, child) in items.iter().enumerate() {
                assert_sorted(child, &format!("{pointer}/{index}"));
            }
        }
        _ => {}
    }
}

/// `a_sealed_bundle_verifies_its_own_digest` — the bytes alone reproduce both
/// recorded digests, and either recorded value being changed fails the check.
#[test]
fn a_sealed_bundle_verifies_its_own_digest() {
    let tree = TempTree::new("sealed-self-check");
    let fixture = ManifestFixture::default();
    write_release_package(&tree, &fixture);
    let spec = SpecFixture::for_packages(vec![SpecEntryFixture::of(&tree, &fixture)]);
    let bundle = checked(&tree, &spec);
    let sealed = bundle.bundle_json();
    let bytes = canonical_bytes(&sealed);

    let parsed = SealedBundle::parse(&bytes).expect("the sealed bytes parse");
    parsed
        .verify()
        .expect("the sealed bundle carries everything its digests need");

    let tampered = json_set(&sealed, "bundle_digest", Json::Str(zero_digest()));
    let error = SealedBundle::from_json(tampered)
        .expect("the shape is still valid")
        .verify()
        .expect_err("a rewritten bundle_digest is not the file's identity");
    assert_eq!(error.code(), "digest-mismatch");

    let tampered = json_set(&sealed, "definition_digest", Json::Str(zero_digest()));
    let error = SealedBundle::from_json(tampered)
        .expect("the shape is still valid")
        .verify()
        .expect_err("a rewritten definition_digest is not the document's identity");
    assert_eq!(error.code(), "digest-mismatch");
}

/// `the_sealed_bundle_key_set_is_exactly_nine_keys` — the file carries the whole
/// `bundle_digest` preimage and nothing else; `sources`, `path`, `builder` and
/// `release_digest` are unknown keys, not optional extras.
#[test]
fn the_sealed_bundle_key_set_is_exactly_nine_keys() {
    let tree = TempTree::new("sealed-nine-keys");
    let fixture = ManifestFixture::default();
    write_release_package(&tree, &fixture);
    let spec = SpecFixture::for_packages(vec![SpecEntryFixture::of(&tree, &fixture)]);
    let bundle = checked(&tree, &spec);
    let sealed = bundle.bundle_json();

    let mut keys: Vec<&str> = sealed
        .as_object()
        .expect("the sealed bundle is an object")
        .iter()
        .map(|(key, _)| key.as_str())
        .collect();
    keys.sort_unstable();
    assert_eq!(
        keys,
        [
            "bundle_digest",
            "bundle_format",
            "bundle_id",
            "definition",
            "definition_digest",
            "definition_format",
            "form_owners",
            "packages",
            "target",
        ]
    );

    for extra in ["sources", "path", "builder", "release_digest"] {
        let value = with_extra(&sealed, extra, Json::Null);
        let error = match SealedBundle::from_json(value) {
            Ok(bundle) => bundle.verify().expect_err("an extra key is never ignored"),
            Err(error) => error,
        };
        assert_eq!(error.code(), "document-shape");
    }
}

/// `the_form_owner_map_is_complete_and_inside_the_digest` — one row per form,
/// every owner inside `packages`, and a rewritten row is a different bundle.
#[test]
fn the_form_owner_map_is_complete_and_inside_the_digest() {
    let tree = TempTree::new("owner-map");
    let (sealed, a, b) = two_package_bundle(&tree);
    let parsed = SealedBundle::from_json(sealed.clone()).expect("the sealed file parses");
    let metadata = parsed.metadata().expect("metadata");
    let owners = owners_of(&metadata);
    assert_eq!(owners.len(), 3, "one row per merged form");

    // Every row names an entry in `packages`, and every form has one row.
    let packages: Vec<&str> = parsed
        .packages()
        .iter()
        .map(|package| package.package_id.as_str())
        .collect();
    for row in &owners {
        let package_id = row.get("package_id").and_then(Json::as_str).unwrap();
        assert!(
            packages.contains(&package_id),
            "{package_id} is not a package"
        );
    }
    let form_ids: Vec<&str> = parsed
        .form_owners()
        .iter()
        .map(|row| row.form_id.as_str())
        .collect();
    let mut sorted = form_ids.clone();
    sorted.sort_unstable();
    assert_eq!(form_ids, sorted, "the rows are sorted by form_id");

    // A missing row.
    let missing = Json::Array(owners[..2].to_vec());
    assert_eq!(
        reject(reseal(&sealed, missing)).code(),
        "bundle-owner-incomplete"
    );

    // A duplicated row.
    let duplicate = Json::Array(vec![owners[0].clone(), owners[0].clone()]);
    assert_eq!(
        reject(reseal(&sealed, duplicate)).code(),
        "bundle-owner-incomplete"
    );

    // A row for a form the definition does not carry.
    let absent = Json::Object(vec![
        (
            "form_id".to_string(),
            Json::Str("x86:absent/form".to_string()),
        ),
        ("package_id".to_string(), owner(&a.package_id)),
    ]);
    let mut extra = owners.clone();
    extra.insert(0, absent);
    assert_eq!(
        reject(reseal(&sealed, Json::Array(extra))).code(),
        "bundle-owner-incomplete"
    );

    // An owner outside `packages`.
    let mut ghost = owners.clone();
    ghost[0] = Json::Object(vec![
        (
            "form_id".to_string(),
            ghost[0].get("form_id").cloned().unwrap(),
        ),
        (
            "package_id".to_string(),
            Json::Str("monasm.x86.ghost".to_string()),
        ),
    ]);
    assert_eq!(
        reject(reseal(&sealed, Json::Array(ghost))).code(),
        "bundle-owner-incomplete"
    );

    // The map is inside the digest: swapping one owner changes the identity even
    // though every form and package row is unchanged.
    let mut swapped = owners.clone();
    let other = if swapped[0].get("package_id").and_then(Json::as_str).unwrap() == a.package_id {
        b.package_id.clone()
    } else {
        a.package_id.clone()
    };
    swapped[0] = Json::Object(vec![
        (
            "form_id".to_string(),
            swapped[0].get("form_id").cloned().unwrap(),
        ),
        ("package_id".to_string(), owner(&other)),
    ]);
    let rewritten = json_set(&metadata, "form_owners", Json::Array(swapped));
    assert_ne!(
        fmp_definition::digest::bundle_digest(&rewritten),
        fmp_definition::digest::bundle_digest(&metadata),
        "one rewritten owner row is a different bundle identity"
    );
}

/// `a_bundle_id_may_advance_to_a_new_definition` — one `bundle_id` may name a
/// new package version over time, but two live specs that share it conflict.
#[test]
fn a_bundle_id_may_advance_to_a_new_definition() {
    let tree = TempTree::new("bundle-advance");
    let v1 = ManifestFixture::default();
    write_release_package(&tree, &v1);
    let spec_a = SpecFixture::for_packages(vec![SpecEntryFixture::of(&tree, &v1)]);
    let first = checked(&tree, &spec_a);

    let v2 = ManifestFixture {
        version: "0.2.0".to_string(),
        ..ManifestFixture::default()
    };
    write_release_package(&tree, &v2);
    let mut spec_b = SpecFixture::for_packages(vec![SpecEntryFixture::of(&tree, &v2)]);
    spec_b.version = "0.1.1-h2".to_string();
    let second = checked(&tree, &spec_b);

    assert_eq!(
        first.bundle_json().get("bundle_id").and_then(Json::as_str),
        second.bundle_json().get("bundle_id").and_then(Json::as_str),
        "the advance keeps the bundle name"
    );
    assert_ne!(first.definition_digest(), second.definition_digest());
    assert_ne!(first.bundle_digest(), second.bundle_digest());

    let a = parse_spec(&spec_a).expect("spec a parses");
    let b = parse_spec(&spec_b).expect("spec b parses");
    let error = fmp_definition::spec::check_spec_set(&[a, b])
        .expect_err("two live specs cannot share a name");
    assert_eq!(error.code(), "bundle-id-conflict");
}

/// `two_specs_cannot_share_a_bundle_or_definition_identity` — `bundle_id` and
/// `(namespace, version)` are each unique across the live set, independently.
#[test]
fn two_specs_cannot_share_a_bundle_or_definition_identity() {
    let base = SpecFixture::for_packages(vec![entry_with_dummy_digest(
        "monasm.x86.example",
        "0.1.0",
        "packages/x86_64/monasm.x86.example/0.1.0",
    )]);

    let mut shared_bundle = base.clone();
    shared_bundle.version = "0.2.0-h2".to_string();
    let error = fmp_definition::spec::check_spec_set(&[
        parse_spec(&base).expect("base parses"),
        parse_spec(&shared_bundle).expect("the variant parses"),
    ])
    .expect_err("a shared bundle_id cannot describe two releases");
    assert_eq!(error.code(), "bundle-id-conflict");

    let mut shared_identity = base.clone();
    shared_identity.bundle_id = "monasm.bundle.x86.other".to_string();
    let error = fmp_definition::spec::check_spec_set(&[
        parse_spec(&base).expect("base parses"),
        parse_spec(&shared_identity).expect("the variant parses"),
    ])
    .expect_err("a shared definition identity names two documents");
    assert_eq!(error.code(), "definition-identity-conflict");

    let mut distinct = base.clone();
    distinct.bundle_id = "monasm.bundle.x86.other".to_string();
    distinct.version = "0.2.0-h2".to_string();
    fmp_definition::spec::check_spec_set(&[
        parse_spec(&base).expect("base parses"),
        parse_spec(&distinct).expect("the distinct spec parses"),
    ])
    .expect("two distinct names are legal");
}
